const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'assets/icons');
const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));
const symbols = [], widths = [];

for (const icon of manifest.icons) {
    if (!/^(?:ri|fa)-[a-z0-9-]+$/.test(icon.id) || icon.source !== `sources/${icon.id}.svg`) throw new Error('Invalid icon manifest entry');
    const source = fs.readFileSync(path.join(directory, icon.source), 'utf8');
    if (crypto.createHash('sha256').update(source).digest('hex') !== icon.sha256) throw new Error(`Source checksum mismatch: ${icon.id}`);
    const svg = source.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/);
    const viewBox = svg?.[1].match(/\bviewBox="([^"]+)"/)?.[1];
    if (!viewBox || /<(?:script|foreignObject|image|use)\b|\bon\w+\s*=|\b(?:href|url\s*\()/i.test(svg[2])) throw new Error(`Unsupported SVG: ${icon.id}`);
    const [x, y, width, height] = viewBox.split(/\s+/).map(Number);
    if (x !== 0 || y !== 0 || !(width > 0 && height > 0)) throw new Error(`Invalid viewBox: ${icon.id}`);
    symbols.push(`<symbol id="${icon.id}" viewBox="${viewBox}">${svg[2].trim()}</symbol>`);
    if (width !== height) widths.push(`.bh-icon.${icon.id} { --bh-icon-width: ${width / height}em; }`);
}

const css = `/* Generated by scripts/build-icons.cjs. Source licenses: assets/icons/licenses/. */
.bh-icon {
    display: inline-block;
    height: 1em;
    font-style: normal;
    vertical-align: -0.125em;
}

.bh-icon.fa-solid,
.bh-icon.fa-brands {
    display: inline-block;
    line-height: 1;
    font-variant: normal;
    text-rendering: auto;
}

.bh-icon-svg {
    display: block;
    width: var(--bh-icon-width, 1em);
    height: 1em;
    overflow: visible;
    fill: currentColor;
    pointer-events: none;
}

/* Keep the advance spacing previously supplied by the icon-font glyph. */
.btn-glass .bh-icon {
    padding-inline-end: var(--btn-glass-letter-spacing);
}

.btn-glass .bh-icon-svg {
    filter: drop-shadow(0 0 0 transparent);
    transition: filter 0.3s ease;
}

/* SVG shadows use sigma: 2.5px matches the existing glass text shadow's 5px blur. */
.container-btn .btn-glass:hover .bh-icon-svg {
    filter: drop-shadow(0 0 2.5px var(--primary-white));
}

.container-btn .btn-glass .is-loading .bh-icon-svg {
    filter: drop-shadow(0 0 5px var(--white-alpha-70));
}

.btn-terminal-sm .bh-icon {
    padding-inline-end: 1px;
}

.card-header .bh-icon {
    padding-inline-end: calc(0.68rem * 0.09);
}

${widths.join('\n')}
`;
const outputs = new Map([
    [path.join(directory, 'icons.svg'), `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`],
    [path.join(root, 'assets/css/icons.css'), css]
]);
for (const [file, content] of outputs) {
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(file, 'utf8') !== content) throw new Error(`Rebuild local icons: ${file}`);
    } else fs.writeFileSync(file, content);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} ${symbols.length} local SVG symbols. No packages or network required.`);
