const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const outputPrefix = 'assets/images/generated/';
const manifestFile = outputPrefix + 'manifest.json';
const runtimeFile = 'assets/js/modules/projects-media.js';
const cardSizes = '(max-width: 768px) calc(100vw - 32px), (max-width: 800px) calc(100vw - 100px), (max-width: 1024px) calc((100vw - 130px) / 2), (max-width: 1120px) calc(100vw - 420px), (max-width: 1460px) calc((100vw - 450px) / 2), (max-width: 1820px) calc((100vw - 480px) / 3), calc((100vw - 510px) / 4)';
const recipe = { version: 1, jpegQuality: 98, projectWidths: [640, 960], logoWidths: [625, 1250], iconWidths: [32, 180, 192],
    minimumSaving: 0.1, minimumPsnr: 45, maximumMeanError: 1, png: { compressionLevel: 9, adaptiveFiltering: true } };
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const read = file => fs.readFile(path.join(root, file));
const normalized = text => text.replace(/\r\n/g, '\n');
sharp.concurrency(2);

function generatedPath(file) {
    const target = path.resolve(root, file), directory = path.resolve(root, outputPrefix);
    if (!file.startsWith(outputPrefix) || !target.startsWith(directory + path.sep)) throw Error(`Invalid generated path: ${file}`);
    return target;
}

function renderRuntime(projects) {
    return `/* Generated by scripts/build-media.cjs. Keep originals in projects-data.js. */\n(function (namespace) {\n    'use strict';\n    namespace.previewMedia = ${JSON.stringify({ cardSizes, sources: projects }, null, 4)};\n})(window.BlackholeSystemsProjects = window.BlackholeSystemsProjects || {});\n`;
}

function quality(reference, encoded) {
    if (reference.length !== encoded.length) throw Error('Decoded dimensions differ');
    let square = 0, absolute = 0;
    for (let i = 0; i < reference.length; i++) {
        const delta = reference[i] - encoded[i]; square += delta * delta; absolute += Math.abs(delta);
    }
    return { psnr: square ? 10 * Math.log10(255 * 255 / (square / reference.length)) : 100, meanError: absolute / reference.length };
}

async function projectRecords() {
    const context = vm.createContext({ window: {} });
    vm.runInContext((await read('assets/js/modules/projects-data.js')).toString('utf8'), context);
    return JSON.parse(JSON.stringify(context.window.BlackholeSystemsProjects.projects))
        .filter(project => project.preview?.src).map(project => ({ id: project.id, ...project.preview }));
}

async function check() {
    const manifest = JSON.parse((await read(manifestFile)).toString('utf8'));
    if (manifest.recipeHash !== hash(normalized((await fs.readFile(__filename, 'utf8'))))) throw Error('Media recipe changed; run npm run build:media');
    if (manifest.encoder.sharp !== sharp.versions.sharp || manifest.encoder.vips !== sharp.versions.vips) throw Error('Encoder version differs; use the pinned development dependencies');
    for (const source of manifest.sources) {
        if (hash(await read(source.src)) !== source.sha256) throw Error(`Master changed: ${source.src}; rebuild media`);
    }
    for (const asset of manifest.assets) {
        generatedPath(asset.src);
        const bytes = await read(asset.src), meta = await sharp(bytes).metadata();
        if (hash(bytes) !== asset.sha256 || bytes.length !== asset.bytes || meta.width !== asset.width || meta.height !== asset.height) throw Error(`Generated asset changed: ${asset.src}`);
    }
    const records = await projectRecords();
    if (JSON.stringify(records) !== JSON.stringify(manifest.projectRecords)) throw Error('Project preview records changed; rebuild media');
    if (normalized((await read(runtimeFile)).toString('utf8')) !== renderRuntime(manifest.projects)) throw Error('Generated preview registry is stale');
    console.log(`Verified ${manifest.assets.length} generated media files and ${records.length} original preview contracts.`);
    return manifest;
}

async function build() {
    const outputs = new Map(), sources = [], assets = [], projects = {}, rejected = [];
    const records = await projectRecords();
    const sourceCache = new Map();
    async function master(src) {
        if (!sourceCache.has(src)) {
            const bytes = await read(src), metadata = await sharp(bytes).metadata();
            if (metadata.orientation && metadata.orientation !== 1) throw Error(`Review oriented master before resizing: ${src}`);
            const source = { src, sha256: hash(bytes), bytes: bytes.length, width: metadata.width, height: metadata.height };
            sources.push(source); sourceCache.set(src, { bytes, source });
        }
        return sourceCache.get(src);
    }
    async function emit(src, bytes, source, extra = {}) {
        generatedPath(src);
        const metadata = await sharp(bytes).metadata();
        const asset = { src, width: metadata.width, height: metadata.height, bytes: bytes.length, sha256: hash(bytes), source: source.src, ...extra };
        if (asset.width * source.height !== asset.height * source.width) throw Error(`Generated aspect differs from master: ${src}`);
        assets.push(asset); outputs.set(src, bytes);
        return { src: asset.src, width: asset.width, height: asset.height };
    }

    const hero = await master('assets/images/blackhole-fallback.png');
    const png = await sharp(hero.bytes).keepIccProfile().png(recipe.png).toBuffer();
    const originalPixels = await sharp(hero.bytes).ensureAlpha().raw().toBuffer();
    if (!originalPixels.equals(await sharp(png).ensureAlpha().raw().toBuffer())) throw Error('Hero recompression changed decoded pixels');
    await emit(outputPrefix + 'blackhole-fallback.png', png.length < hero.bytes.length ? png : hero.bytes, hero.source, { lossless: true });

    const logo = await master('assets/images/logo_bhws_w.png');
    for (const width of recipe.logoWidths) {
        const height = width * logo.source.height / logo.source.width;
        if (!Number.isInteger(height)) throw Error('Logo variants must keep the exact master aspect');
        const pipeline = sharp(logo.bytes).resize({ width, height, withoutEnlargement: true, kernel: 'lanczos3' });
        const bytes = await pipeline.clone().keepIccProfile().png(recipe.png).toBuffer();
        if (bytes.length >= logo.bytes.length) throw Error(`Logo variant is not smaller: ${width}px`);
        if (!(await pipeline.clone().ensureAlpha().raw().toBuffer()).equals(await sharp(bytes).ensureAlpha().raw().toBuffer())) throw Error('Logo encoding changed resized RGBA values');
        await emit(outputPrefix + `logo-${width}.png`, bytes, logo.source, { lossless: true });
    }

    const icon = await master('assets/images/favicon.png');
    for (const width of recipe.iconWidths) {
        const pipeline = sharp(icon.bytes).resize({ width, height: width, withoutEnlargement: true, kernel: 'lanczos3' });
        const bytes = await pipeline.clone().keepIccProfile().png(recipe.png).toBuffer();
        if (bytes.length >= icon.bytes.length) throw Error(`Icon variant is not smaller: ${width}px`);
        if (!(await pipeline.clone().ensureAlpha().raw().toBuffer()).equals(await sharp(bytes).ensureAlpha().raw().toBuffer())) throw Error('Icon encoding changed resized RGBA values');
        await emit(outputPrefix + `favicon-${width}.png`, bytes, icon.source, { lossless: true });
    }

    for (const record of records) {
        if (!/^assets\/images\/projects\/bh-\d{3}-[a-z0-9-]+\.jpg$/.test(record.src)) throw Error(`Unsupported preview master path: ${record.src}`);
        const { bytes: original, source } = await master(record.src);
        if (record.width !== source.width || record.height !== source.height) throw Error(`Preview dimensions differ: ${record.id}`);
        const candidates = [];
        for (const width of recipe.projectWidths) {
            const height = width * source.height / source.width;
            if (!Number.isInteger(height) || width >= source.width) {
                rejected.push({ source: source.src, width, reason: 'exact-aspect-or-size' }); continue;
            }
            const pipeline = sharp(original).resize({ width, height, withoutEnlargement: true, kernel: 'lanczos3', fastShrinkOnLoad: false });
            const encoded = await pipeline.clone().keepIccProfile().jpeg({ quality: recipe.jpegQuality, chromaSubsampling: '4:4:4', mozjpeg: true }).toBuffer();
            if (encoded.length > original.length * (1 - recipe.minimumSaving)) {
                rejected.push({ source: source.src, width, reason: 'insufficient-byte-saving', bytes: encoded.length }); continue;
            }
            const comparison = quality(await pipeline.clone().raw().toBuffer(), await sharp(encoded).raw().toBuffer());
            if (comparison.psnr < recipe.minimumPsnr || comparison.meanError > recipe.maximumMeanError) {
                rejected.push({ source: source.src, width, reason: 'quality-gate', ...comparison }); continue;
            }
            candidates.push(await emit(outputPrefix + 'projects/' + path.posix.basename(record.src, '.jpg') + `-${width}.jpg`, encoded, source, comparison));
        }
        if (candidates.length) projects[record.src] = candidates;
    }

    const manifest = { schema: 1, generator: 'scripts/build-media.cjs', recipeHash: hash(normalized(await fs.readFile(__filename, 'utf8'))),
        encoder: { sharp: sharp.versions.sharp, vips: sharp.versions.vips }, recipe, projectRecords: records, sources, assets, projects, rejected };
    let previous;
    try { previous = JSON.parse((await read(manifestFile)).toString('utf8')); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (previous && (previous.schema !== 1 || previous.generator !== manifest.generator)) throw Error('Unknown media output ownership');
    // Only remove obsolete files explicitly owned by this generator's previous manifest.
    for (const asset of previous?.assets || []) if (!outputs.has(asset.src)) await fs.unlink(generatedPath(asset.src)).catch(error => { if (error.code !== 'ENOENT') throw error; });
    for (const [file, bytes] of outputs) {
        const target = generatedPath(file); await fs.mkdir(path.dirname(target), { recursive: true }); await fs.writeFile(target, bytes);
    }
    await fs.writeFile(path.join(root, manifestFile), JSON.stringify(manifest, null, 2) + '\n');
    await fs.writeFile(path.join(root, runtimeFile), renderRuntime(projects));
    console.log(`Built ${assets.length} media files; retained all masters and ${records.length} original modal previews.`);
    return manifest;
}

module.exports = { build, check, recipe, cardSizes, renderRuntime, quality };
if (require.main === module) (process.argv.includes('--check') ? check() : build()).catch(error => { console.error(error); process.exitCode = 1; });
